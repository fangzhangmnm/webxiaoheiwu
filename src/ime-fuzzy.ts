// 十对 = Windows 微软拼音「模糊拼音」那一页的十对（user 截图）；每对双向。存在 synced prefs `imeFuzzy`（FuzzyPair[]，缺省 = 全关）。
//
// 规则写法：每条把改动的那一段写成大写，最后一条 xlit 统一转回小写。规则只认小写 → 同一个位置不接力
//   （n,l + l,r 同开：n↔l、l↔r，但 n 不会经 l 变成 r），不同位置照样叠加（zh,z + eng,en：zen → zheng）。

export const FUZZY_PAIRS = ["zh-z", "ch-c", "sh-s", "n-l", "l-r", "ang-an", "eng-en", "ing-in", "f-h", "wang-huang"] as const;
export type FuzzyPair = (typeof FUZZY_PAIRS)[number];
export const isFuzzyPair = (v: unknown): v is FuzzyPair => (FUZZY_PAIRS as readonly string[]).includes(v as string);

const RULES: Record<FuzzyPair, readonly string[]> = {
  "zh-z": ["derive/^zh/Z/", "derive/^z([^h])/ZH$1/"],
  "ch-c": ["derive/^ch/C/", "derive/^c([^h])/CH$1/"],
  "sh-s": ["derive/^sh/S/", "derive/^s([^h])/SH$1/"],
  "n-l": ["derive/^n([aeiouv])/L$1/", "derive/^l([aeiouv])/N$1/"],   // 不碰「ng」（嗯）
  "l-r": ["derive/^l([aeiou])/R$1/", "derive/^r([aeiou])/L$1/"],
  "ang-an": ["derive/ang$/AN/", "derive/an$/ANG/"],   // 含 ian ↔ iang、uan ↔ uang
  "eng-en": ["derive/eng$/EN/", "derive/en$/ENG/"],
  "ing-in": ["derive/ing$/IN/", "derive/in$/ING/"],
  "f-h": ["derive/^f/H/", "derive/^h/F/"],   // 只换声母（fa ↔ ha、fei ↔ hei），同 n,l 的写法
  "wang-huang": ["derive/^wang$/HUANG/", "derive/^huang$/WANG/"],
};
const TO_LOWER = "xlit/ABCDEFGHIJKLMNOPQRSTUVWXYZ/abcdefghijklmnopqrstuvwxyz/";

/** 有拼音拼写的方案 → 它的 prism 文件名（语句流和全拼共用 luna_pinyin 的 prism）。五笔不在表里 = 不适用。 */
const PRISM_OF: Record<string, string> = {
  luna_pinyin: "luna_pinyin", luna_pinyin_fluency: "luna_pinyin",
  double_pinyin_mspy: "double_pinyin_mspy", double_pinyin: "double_pinyin", double_pinyin_flypy: "double_pinyin_flypy",
  double_pinyin_abc: "double_pinyin_abc", double_pinyin_pyjj: "double_pinyin_pyjj",
};
export const fuzzyApplies = (schema: string): boolean => schema in PRISM_OF;

/** 任意输入（synced prefs 里的值）→ 合法、去重、按 FUZZY_PAIRS 的顺序。 */
export function normalizeFuzzy(v: unknown): FuzzyPair[] {
  const set = new Set(Array.isArray(v) ? v.filter(isFuzzyPair) : []);
  return FUZZY_PAIRS.filter((p) => set.has(p));
}

/** 这几对 → 插在方案原有拼写规则前面的那一串（空 = 不开）。 */
export function fuzzyRules(pairs: readonly FuzzyPair[]): string[] {
  const on = normalizeFuzzy(pairs);
  return on.length ? [...on.flatMap((p) => RULES[p]), TO_LOWER] : [];
}

const unquote = (s: string): string =>
  s.startsWith('"') && s.endsWith('"') ? s.slice(1, -1).replace(/\\(["\\])/g, "$1")
  : s.startsWith("'") && s.endsWith("'") ? s.slice(1, -1).replace(/''/g, "'")
  : s;
const quote = (s: string): string => `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;

/** 编译好的方案 yaml（`build/<方案>.schema.yaml`，rime-contrib 发的就是这种）里的 speller/algebra。找不到 = 抛错（不猜）。 */
export function readAlgebra(compiledSchemaYaml: string): string[] {
  const lines = compiledSchemaYaml.split(/\r?\n/);
  let i = lines.indexOf("speller:");
  if (i < 0) throw new Error("schema has no speller section");
  for (i++; i < lines.length && lines[i] !== "  algebra:"; i++) if (!/^(\s|$)/.test(lines[i]!)) throw new Error("speller has no algebra");
  if (i >= lines.length) throw new Error("speller has no algebra");
  const out: string[] = [];
  for (i++; i < lines.length; i++) { const m = /^    - (.*)$/.exec(lines[i]!); if (!m) break; out.push(unquote(m[1]!.trim())); }
  if (!out.length) throw new Error("speller algebra is empty");
  return out;
}

/** `<方案>.custom.yaml` 的全文；不开 / 方案不适用 = null（应当删掉这个文件）。内容同时是「这台设备上编过哪一版」的记号：和现存文件逐字相同 = 不用重新部署。 */
export function fuzzyCustomYaml(schema: string, compiledSchemaYaml: string, pairs: readonly FuzzyPair[]): string | null {
  const rules = fuzzyRules(pairs);
  if (!rules.length || !fuzzyApplies(schema)) return null;
  const algebra = [...rules, ...readAlgebra(compiledSchemaYaml)];
  return `# fuzzy pinyin: generated by WebXiaoHeiWu from synced preference imeFuzzy (${normalizeFuzzy(pairs).join(", ")}); edits are overwritten\npatch:\n  speller/algebra:\n${algebra.map((r) => `    - ${quote(r)}`).join("\n")}\n`;
}

/** 部署要的「源」方案：编译版去掉 import_preset（default / symbols 早已并进来了；留着它 RIME 会去找本机没有的 default.yaml / symbols.yaml）。 */
export const sourceSchemaYaml = (compiledSchemaYaml: string): string => compiledSchemaYaml.replace(/^\s*import_preset: .*(\r?\n|$)/gm, "");

/** 关掉 / 还原时要删的文件（相对 /rime）：所有拼音方案的补丁 + 编出来的方案与 prism。删光 = 回到 vendored 预编译那份。 */
export function fuzzyArtifacts(): string[] {
  const out = new Set<string>();
  for (const [schema, prism] of Object.entries(PRISM_OF)) { out.add(`${schema}.custom.yaml`); out.add(`build/${schema}.schema.yaml`); out.add(`build/${prism}.prism.bin`); }
  return [...out];
}
/** 用户词库同步不带这些（能从偏好重新生成；带上会把别的设备的编译产物写回来）。路径相对 /rime。 */
export const isFuzzyArtifactPath = (rel: string): boolean => rel === "build" || rel.startsWith("build/") || rel.endsWith(".custom.yaml");
